export type Say = ReturnType<typeof T>;

/**
 * The titles of the door's buttons (English). The one place they are written: every text that names a
 * button (the card for a friend call, what the Caller connector tells Claude) takes its name from here, so it matches the button shown.
 */
export const buttonLabels = (l: Lang = "en"): { call: string; send: string; cancel: string; undo: string } => {
  const t = T(l);
  return { call: t("btnCall"), send: t("btnSend"), cancel: t("btnCancel"), undo: t("btnUndo") };
};

/** The words that say how a call ended, for the owner (written here from the call's own report; no model involved). */
export function callOutcome(name: string, info: Record<string, unknown>, l: Lang = "en"): string {
  const t = T(l);
  const status = String(info.call_status ?? "");
  const reason = String(info.disconnection_reason ?? "");
  const secs = typeof info.duration_seconds === "number" ? info.duration_seconds : null;
  const long = secs === null ? "" : t("callSeconds", { s: secs });
  if (status === "error" || status === "not_connected") return t("callNotConnected", { name });
  // The same recording on every call so far: it plays on the line before any phone rings, so the fault is the line, not the friend.
  if (/zadarma/i.test(String(info.transcript ?? ""))) return t("callZadarma", { name, at: secs === null ? "" : t("callZadarmaAt", { s: secs }) });
  if (info.call_successful === true) return t("callGiven", { name, long });
  const why: Record<string, Parameters<Say>[0]> = {
    dial_no_answer: "callNoAnswer",
    dial_busy: "callBusy",
    dial_failed: "callDialFailed",
    voicemail_reached: "callVoicemail",
    machine_detected: "callMachine",
  };
  const key = Object.hasOwn(why, reason) ? why[reason] : undefined;
  return key ? t(key, { name }) : t("callUnclear", { name, long });
}
